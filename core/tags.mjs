const norm = (s) => String(s ?? '').toLowerCase();

function hitList(text, table) {
  const t = norm(text);
  const out = [];
  for (const [tag, words] of Object.entries(table)) {
    if (words.some((w) => t.includes(norm(w)))) out.push(tag);
  }
  return out;
}

const arcaChannel = (url) => (String(url).match(/arca\.live\/b\/([^/?#]+)/) ?? [])[1] ?? '';

/** 글 하나 → 태그 배열 (최소 하나, 없으면 ['기타']) */
export function tagRow(r) {
  const found = new Set();

  // 1. 게시판 id 가 곧 주제인 곳
  const byId = BOARD_ID[r.site]?.[r.board];
  if (byId) found.add(byId);

  // 2. 아카라이브 채널
  if (r.site === 'arca') {
    const ch = arcaChannel(r.url);
    for (const [tag, list] of Object.entries(ARCA)) if (list.includes(ch)) found.add(tag);
  }

  // 3. 디시 갤러리 이름 (통합검색은 board 에 갤러리 이름이 들어 있다)
  if (!found.size && r.site === 'dcsearch' && r.board) {
    for (const t of hitList(r.board, BOARD)) found.add(t);
  }

  // 4. 그래도 없으면 제목 + 본문 발췌
  if (!found.size) {
    for (const t of hitList(`${r.title ?? ''} ${r.body ?? ''}`, TEXT)) found.add(t);
  }

  // 2개 넘게 걸리면 대개 넓은 단어가 우연히 겹친 것이다. 앞의 2개만 둔다 (TAGS 순서 기준).
  const list = TAGS.filter((t) => found.has(t)).slice(0, 2);
  return list.length ? list : [OTHER];
}
